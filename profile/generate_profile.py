#!/usr/bin/env python3
"""
Generates the Savant Blueprint component profile from the bridge's state
definitions, so the profile's status parsers always match what the bridge sends.

    python3 generate_profile.py              -> blueprint-import/: kwikset_halolink.xml (8 lock slots),
                                                kwikset_halolink.htm (Documentation tab page, from MANUAL.md + STATES.md)
                                                and kwikset_halolink.icns side by side
    python3 generate_profile.py --locks 12   -> more slots (set max_locks in config.json to match)
    python3 generate_profile.py --test       -> also kwikset_halolinktest.xml (tiny, for import troubleshooting)

Structure:
  * Ethernet/TCP control, KEY=value status lines: same proven layout as Savant OpenWx.
  * Native Savant Door Lock service, laid out like Savant's own August Smart Lock profile
    (v1.17): device_class DoorLock_controller, internal "Door Lock" with ENV_DOOR_LOCK_SOURCE,
    LockDoorLock / UnlockDoorLock (DoorLockAddress, DoorLockAddress2), a Lock entity bound to
    DoorLockStatus, GetLockStatus queried at startup and daily, and the same state names
    (DoorLockStatus_n, IsDoorLocked_n, DoorStatus_n, IsDoorClosed_n, BatteryLevel_n).
    Difference: August uses one profile instance per lock; here one instance serves every
    lock and the entity address (DoorLockAddress) is the lock number.
  * Custom actions + LOCKn_* states for triggers, custom screens and anything the
    native service doesn't cover (battery, door sensor, LED/audio/auto-lock settings).
"""
