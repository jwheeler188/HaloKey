def body(model, locks, defs, actions_xml, resource=True):
    return "\n".join([
        head(model, locks),
        f'    <logical_component logical_component_name="{LC}">',
        "        <implementation>",
        '            <internal name_on_component="Door Lock"/>',
        "        </implementation>",
        status_messages(defs),
        door_lock_resource() if resource else "",
        actions_xml,
        "    </logical_component>",
        "</component>",
        "",
    ])


def build(locks, test=False):
    defs = state_defs(locks)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body(MODEL, locks, defs, custom_actions(locks)), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE)}: {locks} lock slots, {len(defs)} status parsers")
    if test:
        keep = {"SYS_ONLINE", "SYS_AUTH", "LOCK1_STATUS", "DoorLockStatus_1", "IsDoorLocked_1"}
        tdefs = [d for d in defs if d[0] in keep]
        acts = ("        <custom_component_actions>"
                + action("Ping", [("text", "PING")]) + action("LockDoor1", [("text", "LOCK 1")])
                + action("GetLockStatus", [("text", "STATUS "), ("arg", "DoorLockAddress")],
                         [("DoorLockAddress", "Lock number"), ("DoorLockAddress2", "not used")])
                + "\n        </custom_component_actions>")
        tout = HERE / profile_filename(MANUFACTURER, MODEL + "Test")
        tout.write_text(body(MODEL + "Test", 1, tdefs, acts), encoding="utf-8")
        print(f"wrote {tout.name}: {len(tdefs)} status parsers (import troubleshooting)")


