        action("RefreshLocks", [("text", "REFRESH")], comment="Ask Kwikset for fresh status now (also finds newly added locks)."),
        action("Ping", [("text", "PING")], schedules=(60000,), comment="Keepalive every minute; the bridge answers PONG."),
