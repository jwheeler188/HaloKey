def status_messages(defs):
    # Each bridge line is KEY=value<LF>; receive_end_condition splits on LF.
    out = ["        <status_messages>"]
    for key, typ, desc in defs:
        if typ == "boolean":
            body = f"""                <data type="character" terminator_type="end_of_data">
                    <data_map match_required="no">
                        <map key="true"><update state="{key}" type="boolean">true</update></map>
                        <map key="false"><update state="{key}" type="boolean">false</update></map>
                    </data_map>
                </data>"""
        else:
            body = f"""                <data type="character" terminator_type="end_of_data">
                    <update state="{key}" type="{typ}"/>
                </data>"""
        out.append(f"""            <status_message name="{key}">
                <constant type="character">{key}=</constant>
{body}
            </status_message>""")
    out.append("        </status_messages>")
    return "\n".join(out)


def command(parts, delay=None):
    """parts: list of ("text", str) / ("arg", argument name) / ("var", state variable).
    A leading "text" part becomes the <command_string> (the OpenWx-proven form, trailing
    space kept); the rest go in <parameter_list>. Arguments are separated with "," rather
    than a bare space so no parameter is whitespace-only."""
    cmd = ""
    if parts and parts[0][0] == "text":
        cmd, parts = parts[0][1], parts[1:]
    params = []
    for kind, val in parts:
        if kind == "text":
            params.append(f'                            <parameter parameter_data_type="character">{escape(val)}</parameter>')
        elif kind == "arg":
            params.append(f'                            <parameter parameter_data_type="character" action_argument="{val}"/>')
        else:
            params.append(f'                            <parameter parameter_data_type="character" state_variable="{val}"/>')
    d = f'\n                        <delay ms_delay="{delay}"/>' if delay else ""
    plist = ""
    if params:
        plist = "\n                        <parameter_list>\n" + "\n".join(params) + "\n                        </parameter_list>"
    return f"""                    <command response_required="no">
                        <command_string type="character">{escape(cmd)}</command_string>{plist}{d}
                    </command>"""


def action(name, parts, args=(), schedules=(), comment=""):
    a = "".join(f'\n                <action_argument name="{n}" note="{attr(note)}"/>' for n, note in args)
    sched = "".join(f'\n                <execute_on_schedule period_ms="{ms}"></execute_on_schedule>' for ms in schedules)
    c = f"\n            <!-- {comment} -->" if comment else ""
    return f"""{c}
            <action name="{name}">{a}
                <command_interface interface="ip">
{command(parts)}
                </command_interface>{sched}
            </action>"""


LOCK_ADDR_ARGS = """
                <action_argument name="DoorLockAddress" note="Lock number from: halolink list"/>
                <action_argument name="DoorLockAddress2" note="not used"/>"""


def door_lock_resource():
    """Savant's native Door Lock service, as in Savant's August profile. DoorLockAddress = lock number."""
    def act(name, verb):
        return f"""
            <action name="{name}">{LOCK_ADDR_ARGS}
                <command_interface interface="ip">
{command([("text", verb + " "), ("arg", "DoorLockAddress")], delay=250)}
                </command_interface>
            </action>"""
    return f"""        <resource_component_actions resource_type="ENV_DOOR_LOCK_SOURCE">{act("LockDoorLock", "LOCK")}{act("UnlockDoorLock", "UNLOCK")}

            <entity name="Lock" address_components="1" default_address_1="1">
                <toggle_button_representation>
                    <press_action name="UnlockDoorLock"/>
                    <toggle_action name="LockDoorLock"/>
                    <osd_press_action name="UnlockDoorLock"/>
                    <osd_hold_action name="LockDoorLock"/>
                    <toggleOnUsingState name="DoorLockStatus">
                        <unique_identifier name="switchID" address_component="1"/>
                    </toggleOnUsingState>
                </toggle_button_representation>
                <query_status_with_action name="GetLockStatus" period_ms="0"/>
                <query_status_with_action name="GetLockStatus" period_ms="86400000"/>
            </entity>
        </resource_component_actions>"""


