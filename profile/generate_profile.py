def docs_html():
    """The whole user manual as the Documentation tab page, with STATES.md as Appendix A."""
    manual = (ROOT / "MANUAL.md").read_text(encoding="utf-8").splitlines()
    states = (ROOT / "STATES.md").read_text(encoding="utf-8").splitlines()
    # Appendix A: STATES.md's own title is dropped and its sections become h3s under the appendix heading
    states = ["#" + l if l.startswith("## ") else l for l in states if not l.startswith("# ")]
    body = md_blocks(manual + [""] + states)
    page = f"""<html>
<head>
<meta http-equiv="Content-Type" content="text/html; charset=us-ascii">
<title>HaloKey {VERSION}</title>
<style>{DOC_CSS}</style>
</head>
<body>
{body}
</body>
</html>
"""
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_bytes(page.encode("ascii", "xmlcharrefreplace"))
    print(f"wrote {DOC.relative_to(HERE)}: Documentation tab ({DOC.stat().st_size // 1024} KB)")


def states_md(locks):
    from halolink_bridge import SYS_STATES, LOCK_FIELDS
    lines = [f"# HaloKey states (v{VERSION})", "",
             "Every state the bridge sends. n = lock number (1 to max_locks) from `halolink list`.", "",
             "## System", "", "| State | Type | Meaning |", "|---|---|---|"]
    lines += [f"| `{k}` | {t} | {d} |" for k, t, d in SYS_STATES]
    lines += ["", "## Per lock (LOCKn_...)", "", "| State | Type | Meaning |", "|---|---|---|"]
    lines += [f"| `LOCKn_{f}` | {t} | {d} |" for f, t, d in LOCK_FIELDS]
    lines += ["", "## Savant Door Lock service", "", "| State | Type | Meaning |", "|---|---|---|",
              "| `DoorLockStatus_n` | string | Locked / Unlocked / Unknown (Jammed shows as Unknown) |",
              "| `IsDoorLocked_n` | boolean | true when Locked |",
              "| `DoorLockError_n` | string | Door Lock data table Error State: blank, or Lock offline / Lock jammed / last command error |",
              "| `DoorStatus_n` | string | Open / Closed / Unknown (door position sensor) |",
              "| `IsDoorClosed_n` | boolean | true when Closed; only sent when the sensor reports |",
              "| `BatteryLevel_n` | float | Battery percent |", ""]
    (HERE.parent / "STATES.md").write_text("\n".join(lines))
    print("wrote STATES.md")


